// Release signing comes from keystore.properties (gitignored) or OPMOCK_* environment variables.
val signingProps = Properties().apply {
    rootProject.file("keystore.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
}
fun signingValue(key: String, env: String): String? = signingProps.getProperty(key) ?: System.getenv(env)
val releaseStoreFile = signingValue("storeFile", "OPMOCK_STORE_FILE")

android {
    namespace = "com.pwc.mockpresence"
    compileSdk = 34

    defaultConfig {
        applicationId = "com.pwc.mockpresence"
        minSdk = 26
        targetSdk = 34
        versionCode = 1
        versionName = "1.0.0"
    }

    signingConfigs {
        if (releaseStoreFile != null) {
            create("release") {
                storeFile = file(releaseStoreFile)
                storePassword = signingValue("storePassword", "OPMOCK_STORE_PASSWORD")
                keyAlias = signingValue("keyAlias", "OPMOCK_KEY_ALIAS")
                keyPassword = signingValue("keyPassword", "OPMOCK_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            if (releaseStoreFile != null) signingConfig = signingConfigs.getByName("release")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
    }
    composeOptions {
        kotlinCompilerExtensionVersion = "1.5.14"
    }
    lint {
        // MainActivity is a ComponentActivity. The old Fragment only comes in through Play Services.
        disable += "InvalidFragmentVersionForActivityResult"
    }
}

